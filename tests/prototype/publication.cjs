// Detect missing publication validation, lost drafts and per-house phone copies.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../../design/prototype'),listeners={};
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:()=>{},document:{addEventListener:(k,f)=>(listeners[k]??=[]).push(f),querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({})}});
const run=s=>vm.runInContext(s,ctx);
run(fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8').match(/<script>([\s\S]*?)<\/script>/)[1]);
run(fs.readFileSync(path.join(root,'relay.js'),'utf8'));
const file=path.join(root,'publication.js');if(fs.existsSync(file))run(fs.readFileSync(file,'utf8'));
assert.equal(run('typeof publicationSubmit'),'function','publication must validate and save a review draft');
run("S.role='owner';publicationReset();publicationSet('kind','apartment')");
assert.equal(run('publication.draft.pool'),'no','amenities start unchecked');
assert.equal(run("'furnished' in publication.draft"),false);
run('S.wizStep=3');
assert.match(run('publicationScreen()'),/type="checkbox"[^>]*data-publication-check="parking"/);
assert.doesNotMatch(run('publicationScreen()'),/pub-parkingType|amueblado/i);
for(const fn of listeners.change||[])fn({target:{dataset:{publicationCheck:'parking'},type:'checkbox',checked:true}});
assert.equal(run('publication.draft.parking'),'yes');
assert.match(run('publicationScreen()'),/pub-parkingType/);
run("publicationSet('parkingType','paid');publicationSet('parking','no')");
assert.equal(run('publication.draft.parkingType'),'','unchecking clears stale payment choice');
run('S.wizStep=1');
assert.equal(run('publicationNext()'),false,'long-term answer must be explicit');
run("publicationSet('acceptsLongTerm','no')");
assert.equal(run('publicationNext()'),true);
assert.equal(run('S.wizStep'),2);
assert.equal(run('publicationNext()'),false,'location cannot be blank');
run("publicationSet('province','Limón');publicationSet('canton','Talamanca');publicationSet('zone','Puerto Viejo')");
assert.equal(run('publicationNext()'),true);
run("publicationSet('people','2');publicationSet('bedrooms','0');publicationSet('bathrooms','1');publicationSet('title','Estudio tranquilo');publicationSet('description','Estudio con cocina y baño privado.');['pets','pool','wifi','ac','parking'].forEach(k=>publicationSet(k,'no'))");
assert.equal(run('publicationNext()'),true,'a studio can have zero bedrooms');
run("S.wizStep=3;publicationSet('parking','yes')");
assert.match(run('publicationError(3)'),/gratuito o de pago/);
run("publicationSet('parkingType','free')");
assert.equal(run('publicationError(3)'),'');
run("S.wizStep=3;publicationSet('bedrooms','');");
assert.equal(run('publicationNext()'),false,'empty bedrooms must not be coerced to zero');
run("publicationSet('bedrooms','1.5')");assert.equal(run('publicationNext()'),false);
run("publicationSet('bedrooms','0');publicationSet('bathrooms','0')");assert.equal(run('publicationNext()'),false);
run("publicationSet('bathrooms','1');publicationSet('bathroomUse','shared');publicationNext();publication.draft.photoCount=4");
assert.equal(run('publicationNext()'),false);
run('publication.draft.photoCount=5');assert.equal(run('publicationNext()'),true);
run("publicationSet('nightlyPrice','48000');publicationSet('minNights','2')");
assert.equal(run('publicationSubmit()'),true);
assert.equal(run('publication.submitted[0].bathroomUse'),'shared');
assert.equal(run('publication.submitted[0].bedrooms'),0);
assert.equal(run('publication.submitted[0].status'),'review');
assert.equal(run('publication.submitted[0].mode'),'vac');
assert.equal(run("'whatsapp' in publication.submitted[0]"),false);
assert.equal(run('publicationSubmit()'),false,'double submission must not create duplicates');
run("publicationReset();Object.assign(publication.draft,{kind:'room',acceptsLongTerm:'yes',province:'Limón',canton:'Talamanca',zone:'Cahuita',people:'2',bedrooms:'1',bathrooms:'1',title:'Habitación',description:'Habitación para dos.',pets:'no',pool:'no',wifi:'yes',ac:'no',parking:'yes',parkingType:'paid',nightlyPrice:'20000',minNights:'1',photoCount:5})");
assert.equal(run('publicationSubmit()'),false,'monthly price choice cannot be skipped');
run("publicationSet('monthlyMode','amount')");assert.equal(run('publicationSubmit()'),false);
run("publicationSet('monthlyPrice','-1')");assert.equal(run('publicationSubmit()'),false);
run("publicationSet('monthlyMode','contact')");
const publicationClick=dataset=>listeners.click.at(-1)({target:{closest:()=>({dataset})},stopImmediatePropagation:()=>{}});
publicationClick({publicationAccount:''});
assert.match(run("SCREENS['o-whatsapp']()"),/Volver al anuncio/);
publicationClick({publicationReturn:''});
assert.equal(run('S.screen'),'o-new');
assert.equal(run('publicationSubmit()'),true);
assert.doesNotMatch(run("SCREENS['o-whatsapp']()"),/Volver al anuncio/,'account cannot return to an already submitted draft');
publicationClick({publicationReturn:''});
assert.equal(run('publication.sent'),false,'even a stale return action must open a fresh draft');
assert.equal(run('publication.submitted[1].monthlyPrice'),null);
assert.equal(run('publication.submitted[1].parkingType'),'paid');
assert.equal(run('publication.submitted[1].bathroomUse'),'private','default is saved as private');
assert.equal(run("publicationSetWhatsapp('+506 80000000')"),true);
assert.equal(run('publicationPhoneFor(publication.submitted[0])'),'+50680000000');
assert.equal(run('publicationPhoneFor(publication.submitted[1])'),'+50680000000');
assert.equal(run("publicationSetWhatsapp('invalid')"),false);
run("publicationReset();publicationSet('acceptsLongTerm','yes');publicationSet('monthlyMode','amount');publicationSet('monthlyPrice','150000');publicationSet('acceptsLongTerm','no')");
assert.equal(run('publication.draft.monthlyPrice'),'','turning long-term off clears stale monthly pricing');
for(const fn of listeners.input||[])fn({target:{dataset:{publicationField:'title'},value:'Borrador persistente'}});
assert.equal(run('publication.draft.title'),'Borrador persistente');
run("publicationSet('title','<img src=x onerror=alert(1)>');S.wizStep=3");
assert.doesNotMatch(run('publicationScreen()'),/<img src=x/);
run("S.role='guest'");assert.equal(run('publicationSubmit()'),false);
console.log('PASS: publication requirements, conditional prices, state, account phone, escaping and review submission.');

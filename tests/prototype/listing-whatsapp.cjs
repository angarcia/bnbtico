// Catch unverified destinations, cross-house updates and stale verification codes.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../../design/prototype');
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:()=>{},document:{addEventListener:()=>{},querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({})}});
const run=s=>vm.runInContext(s,ctx);
for(const s of fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8').matchAll(/<script(?: src="([^"]+)")?>([\s\S]*?)<\/script>/g))run(s[1]?fs.readFileSync(path.join(root,s[1].split('?')[0]),'utf8'):s[2]);
assert.equal(run('typeof listingPhoneVerify'),'function','per-listing verification flow exists');
run("S.role='owner';var id=MY[0].id,other=MY[1].id;var original=listingPhoneFor(id);houseEdit(id);");
assert.equal(run('listingPhoneCurrent().pending'),run('original'),'editing defaults to current house number');
assert.equal(run("listingPhoneEdit('+506 80000001')"),true);
assert.equal(run('listingPhoneFor(id)'),run('original'),'pending phone must not replace active destination');
assert.equal(run('listingPhoneSave()'),true);
assert.equal(run("listingPhoneVerify('000000')"),false);
assert.equal(run('listingPhoneFor(id)'),run('original'));
assert.equal(run("listingPhoneVerify('123456')"),true);
assert.equal(run('listingPhoneFor(id)'),'+50680000001');
assert.equal(run('listingPhoneFor(other)'),run('original'),'another house keeps its destination');
run("S.role='guest';S.loggedIn=true;var contact=relayCreate(id);contact.ownerConsent=false;");
assert.equal(run('listingPhoneDestination(contact)'),null,'pending consent never exposes the house number');
run("S.role='owner';relayAccept(contact);S.role='guest';");
assert.equal(run('listingPhoneDestination(contact)'),'+50680000001','accepted contact routes to verified house destination');
run("S.role='owner';");
assert.equal(run("listingPhoneVerify('123456')"),false,'codes are single use');
run("listingPhoneEdit('+50680000002');listingPhoneSave();listingPhoneEdit('+50680000003');");
assert.equal(run("listingPhoneVerify('123456')"),false,'editing invalidates pending code');
assert.equal(run('listingPhoneFor(id)'),'+50680000001');
run('listingPhoneSave();relay.clockOffset+=6*60*1000;');
assert.equal(run("listingPhoneVerify('123456')"),false,'code expires');
run("S.role='guest';");assert.equal(run("listingPhoneEdit('+50680000004')"),false);assert.equal(run('listingPhoneSave()'),false);
run("S.role='owner';publicationReset();");
assert.equal(run('listingPhoneCurrent().active'),run('publication.account.whatsapp'),'new house copies verified account default');
run("listingPhoneEdit('+50680000005');");
assert.equal(run('publicationSubmit()'),false,'unverified draft cannot be submitted');
run('listingPhoneSave();');assert.equal(run("listingPhoneVerify('123456')"),true);
run("Object.assign(publication.draft,{kind:'house',acceptsLongTerm:'no',province:'Limón',canton:'Talamanca',zone:'Cahuita',people:'2',bedrooms:'1',bathrooms:'1',title:'Casa demo',description:'Descripción demo',photoCount:5,nightlyPrice:'50000',minNights:'1'});");
assert.equal(run('publicationSubmit()'),true);
assert.equal(run('publicationPhoneFor(publication.submitted.at(-1))'),'+50680000005');
run("publicationSetWhatsapp('+50680000006');publicationReset();");
assert.equal(run('listingPhoneCurrent().active'),null,'unverified account default requires verification');
assert.equal(run('listingPhoneFor(id)'),'+50680000001','account edits do not rewrite verified listing destinations');
assert.equal(run('publicationPhoneFor(publication.submitted.at(-1))'),'+50680000005');
console.log('PASS: per-house WhatsApp defaults, verification, pending retention, scoped destinations, expiry and authorization.');

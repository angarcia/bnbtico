// Catch reviewing the wrong listing, unvalidated decisions, lost reasons and unseen owner submissions.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../../design/prototype'),noop=()=>{};
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:noop,document:{addEventListener:noop,querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({})}});
const run=s=>vm.runInContext(s,ctx),html=fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8');
for(const script of html.matchAll(/<script(?: src="([^"]+)")?>([\s\S]*?)<\/script>/g))run(script[1]?fs.readFileSync(path.join(root,script[1].split('?')[0]),'utf8'):script[2]);
assert.equal(run('typeof adminOpenReview'),'function','admin needs full listing review');
run("S.role='admin'");
assert.equal(run("moderateListing(0,'ok')"),false,'open review before approving');
assert.equal(run('adminOpenReview(0)'),true);
assert.match(run('adminReviewScreen()'),/Loft Caribe/);
assert.match(run('adminReviewScreen()'),/Descripción/);
assert.equal(run('adminSelectPhoto(4)'),true);
assert.match(run('adminReviewScreen()'),/Foto 5 de 5/);
assert.equal(run('adminSelectPhoto(5)'),false,'photo selection is bounded');
assert.equal(run("adminDecide('changes','   ')"),false,'changes require a reason');
assert.equal(run("adminDecide('no','')"),false,'rejection requires a reason');
assert.equal(run('S.queue[0].status'),'pend');
assert.equal(run("adminDecide('changes','Completá los detalles del parqueo.')"),true);
assert.equal(run('S.queue[0].status'),'changes');
assert.equal(run('S.queue[0].decision.reason'),'Completá los detalles del parqueo.');
assert.equal(run("adminDecide('ok','')"),false,'cannot overwrite a completed decision');
run('adminOpenReview(1)');
assert.match(run('adminReviewScreen()'),/Estudio cerca del TEC/);
assert.equal(run("adminDecide('ok','')"),true,'Veriff es opcional (2026-10-13): identidad pendiente no bloquea aprobar');
assert.equal(run('S.queue[1].identityStatus'),'pending','la aprobación no inventa una identidad verificada');
assert.equal(run("adminDecide('no','Descripción incompleta.')"),false,'cannot overwrite a completed decision');
run('adminOpenReview(2)');assert.equal(run("adminDecide('ok','')"),false,'two photos cannot meet the five-photo rule');
run("S.role='owner'");assert.equal(run('adminOpenReview(0)'),false);
assert.doesNotMatch(run('adminReviewScreen()'),/Loft Caribe|Completá los detalles/);
run("Object.assign(publication.draft,{kind:'apartment',acceptsLongTerm:'yes',province:'Limón',canton:'Talamanca',zone:'Cahuita',people:'2',bedrooms:'0',bathrooms:'1',title:'Mi estudio nuevo',description:'Un estudio privado cerca del mar.',pets:'no',pool:'no',wifi:'yes',ac:'yes',parking:'yes',parkingType:'paid',photoCount:5,nightlyPrice:'45000',minNights:'2',monthlyMode:'contact'});publicationSubmit();S.role='admin';adminReviewSync();adminReviewSync();");
assert.equal(run('S.queue.length'),4,'one owner submission creates exactly one review');
run('adminOpenReview(3)');
assert.match(run('adminReviewScreen()'),/Mi estudio nuevo/);
assert.match(run('adminReviewScreen()'),/Un estudio privado cerca del mar/);
assert.match(run('adminReviewScreen()'),/Consultar con el propietario/);
assert.match(run('adminReviewScreen()'),/De pago/);
assert.doesNotMatch(run('adminReviewScreen()'),/Amueblado/);
assert.match(run('adminReviewScreen()'),/45[.\s\u00a0]?000/);
assert.equal(run("adminDecide('ok','Revisado.')"),true);
assert.equal(run('publication.submitted[0].status'),'approved-demo');
assert.equal(run('HOUSES.some(h=>h.t==="Mi estudio nuevo")'),true,'desde 2026-10-13 una casa aprobada entra en el catálogo de la demo (zona-caribe.js)');
run("S.role='owner'");assert.match(run("SCREENS['o-houses']()"),/Aprobada/);
run("S.role='admin';S.queue[3].listing.description='<img src=x onerror=alert(1)>';adminOpenReview(3)");
assert.doesNotMatch(run('adminReviewScreen()'),/<img src=x/);
assert.equal(run('adminOpenReview(999)'),false);
console.log('PASS: full admin review, bounded gallery, decisions/reasons, identity gate and owner submission linkage.');

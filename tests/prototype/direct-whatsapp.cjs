// Catch contact disclosure before consent, duplicate requests, and wrong-role access.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../../design/prototype'),noop=()=>{};
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:noop,document:{addEventListener:noop,querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({value:''})}});
vm.runInContext(fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8').match(/<script>([\s\S]*?)<\/script>/)[1],ctx);
vm.runInContext(fs.readFileSync(path.join(root,'relay.js'),'utf8'),ctx);
const run=s=>vm.runInContext(s,ctx);
run("relay.threads=[];S.leads=[];S.loggedIn=true;relayOpenHouse('CT-1042')");
assert.notEqual(run('S.screen'),'chat','contact must not open an internal conversation');
assert.equal(run('relay.threads.length'),0,'opening alone does not notify the owner');
assert.equal(run("relayRequest('CT-1042',false)"),false,'explicit phone-sharing consent required');
assert.equal(run('S.leads.length'),0);
assert.equal(run("relayRequest('CT-1042',true)"),true);
run('const first=relayCurrent();const expiry=first.expiresAt');
assert.equal(run('relayCanWhatsApp(first)'),false,'owner has not agreed yet');
assert.equal(run('relayAccept(first)'),false,'client cannot accept as owner');
run("relayOpenHouse('CT-1042');relayRequest('CT-1042',true)");
assert.equal(run('relay.threads.length'),1);
assert.equal(run('S.leads.length'),1);
assert.equal(run('first.expiresAt'),run('expiry'));
run("S.role='owner'");
assert.equal(run('relayAccept(first)'),true);
assert.equal(run('relayCanWhatsApp(first)'),true);
run("S.role='guest'");
assert.equal(run('relayCanWhatsApp(first)'),true);
run('relay.clockOffset+=7*DAY_MS');
assert.equal(run('relayCanWhatsApp(first)'),true,'expiry does not retract contacts already accepted');
run("relayRequest('CT-1042',true);const second=relayCurrent()");
assert.notEqual(run('second.id'),run('first.id'));
assert.equal(run('relayCanWhatsApp(second)'),false,'new request does not inherit owner consent');
run("S.role='admin'");
assert.equal(run('relayAccept(second)'),false);
assert.equal(run('relayCanWhatsApp(first)'),false);
run("S.role='guest';S.loggedIn=false");
assert.equal(run("relayRequest('CT-1042',true)"),false);
assert.equal(run('relayCanWhatsApp(first)'),false);
assert.doesNotMatch(run('contactHistory()'),/Villa/);
run("S.loggedIn=true;relayRequest('CT-1088',true);const foreign=relayCurrent();S.role='owner'");
assert.equal(run('relayAccept(foreign)'),false);
assert.doesNotMatch(run('oLeads()'),/Cabina Nube/);
run("S.role='guest';relayOpenOffer('CT-1042',first.id)");
assert.equal(run('relayCurrent().id'),run('first.id'),'history retains original request');
run("S.loggedIn=false;relayOpenOffer('CT-1042',first.id)");
assert.equal(run('S.screen'),'login');
assert.equal(run('S.params.thread'),run('first.id'));
run("S.loggedIn=true;relayOpenHouse('CT-1101')");
assert.equal(run('S.screen'),'detail','after login, closing the request must return to the house, not the registration form');
assert.equal(run('S.params.id'),'CT-1101');
console.log('PASS: solicitud sin chat, consentimiento, aceptación del owner, deduplicación, historial y permisos de demo.');

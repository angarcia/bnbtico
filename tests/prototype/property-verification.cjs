// Historical future module tested in isolation; not loaded or linked by the v1 entry point.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'../../design/prototype');
const noop=()=>{};
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:noop,document:{addEventListener:noop,querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({value:''})}});
vm.runInContext(fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8').match(/<script>([\s\S]*?)<\/script>/)[1],ctx);
for(const file of ['relay.js','claims.js','property.js'])if(fs.existsSync(path.join(root,file)))vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx);
const run=s=>vm.runInContext(s,ctx);
run("S.role='owner'");
assert.match(run('propertyButton(MY[0])'),/Verificar propiedad/);
assert.doesNotMatch(run('ownerCard(MY[0])'),/Verificar propiedad/);
assert.equal(run('propertyStart(MY[0].id)'),true);
assert.equal(run('S.screen'),'o-verify');
assert.match(run('propertyScreen()'),/¿Ya tenés una certificación literal/);
assert.equal(run("propertyStep('guide1')"),true);
assert.match(run('propertyScreen()'),/No sé mi número de finca/);
for(const step of ['guide2','guide3','code'])assert.equal(run(`propertyStep('${step}')`),true);
assert.equal(run("propertyStep('made-up')"),false);
assert.equal(run("propertySubmit('RNPDIGITAL-DEMO-2026',false)"),false,'requires demo consent');
assert.equal(run("propertySubmit('RNPDIGITAL-12345-2026',true)"),false,'does not collect real codes');
assert.equal(run("propertySubmit('',true)"),false);
assert.equal(run("propertySubmit('RNPDIGITAL-DEMO-2026',true)"),true);
assert.equal(run('propertyCurrent().status'),'review');
assert.match(run('propertyScreen()'),/Verificación en revisión/);
assert.doesNotMatch(run('ownerCard(MY[0])'),/>Propietario verificado</);
const created=run('propertyCurrent().submittedAt');
assert.equal(run("propertySubmit('RNPDIGITAL-DEMO-2026',true)"),false,'no duplicate submission');
assert.equal(run('propertyCurrent().submittedAt'),created);
run('propertyStart(MY[1].id)');
assert.equal(run('propertyCurrent().status'),'draft','a second house starts separately');
run("propertyStep('guide2'); go('o-houses'); propertyStart(MY[1].id)");
assert.equal(run('propertyCurrent().step'),'guide2','resume saved in-memory step');
run('propertyStart(MY[0].id)');
assert.equal(run('propertyCurrent().status'),'review','first house remains in review');
assert.equal(run("propertyStart('not-a-house')"),false);
run("S.role='guest'");
assert.equal(run('propertyStart(MY[0].id)'),false);
assert.equal(run("propertySubmit('RNPDIGITAL-DEMO-2026',true)"),false);
assert.doesNotMatch(run('propertyScreen()'),/RNPDIGITAL-DEMO-2026/,'no owner flow exposed to guest');
run("S.role='admin'");
assert.equal(run('propertyStart(MY[0].id)'),false);
console.log('PASS: guía, atajo, roles, código ficticio, consentimiento, revisión sin sello, duplicados y progreso por casa.');

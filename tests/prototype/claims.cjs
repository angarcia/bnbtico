const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'../../design/prototype');
const noop=()=>{};
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:noop,document:{addEventListener:noop,querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({value:''})}});
vm.runInContext(fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8').match(/<script>([\s\S]*?)<\/script>/)[1],ctx);
for(const file of ['relay.js','claims.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx);
const run=s=>vm.runInContext(s,ctx);
run("S.loggedIn=true;S.role='guest';const c=claimCreate({house:'CT-1042',reason:'No se cumplió lo acordado',detail:'No pude acceder al alojamiento.',evidence:'Conversación y recibo de ejemplo',amount:25000,currency:'CRC'});");
assert.equal(run('c.amount'),undefined,'reports must not track requested money');
assert.equal(run('c.currency'),undefined);
assert.equal(run('c.refund'),undefined);
assert.doesNotMatch(run('claimsScreen()'),/claim-amount|claim-currency|Importe solicitado/);
run("S.role='owner'");
for(const action of ['accept','paid','confirm','not_received'])assert.equal(run(`claimAct(c,'${action}','Ejemplo')`),false,'no money workflow');
assert.equal(run('claimAct(c,"respond","")'),false);
assert.equal(run('claimAct(c,"respond","Mi versión de los hechos")'),true);
assert.doesNotMatch(run('claimsScreen()'),/Aceptar devolución|Comunicar devolución|Importe solicitado/);
run("S.role='admin'");
assert.equal(run('claimAct(c,"request_response","Aclarar los hechos")'),true);
assert.equal(run('claimDecide(c,"substantiated","suspension","")'),false);
assert.equal(run('claimDecide(c,"substantiated","suspension","Pruebas y respuesta revisadas")'),true);
assert.equal(run('claimAct(c,"resolve","Revisión concluida")'),true);
assert.equal(run('c.status'),'resolved');
run("S.role='guest'");
assert.equal(run('claimAct(c,"resolve","Cerrar")'),false);
assert.equal(run('claimAct(c,"appeal","Solicito revisar la decisión")'),true);
assert.equal(run('c.status'),'review','reclamación reabre revisión');
assert.equal(run('c.measure'),'suspension');
assert.equal(run('c.history.length>5'),true);
assert.throws(()=>run("claimCreate({house:'CT-1042',detail:'',evidence:'x'})"));
run("S.role='guest'");
assert.match(run('claimsScreen()'),/sin recargos/i);
assert.equal(run('claimDecide(c,"unsubstantiated","none","x")'),false);
console.log('PASS: reports without money fields/actions, owner response, admin decision/closure, appeals and permissions.');

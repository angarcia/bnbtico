// Catch ignored mandatory filters, cross-flow state leaks and unsolicited contacts.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../../design/prototype');
const noop = () => {};
const listeners = {};
const ctx = vm.createContext({console, setTimeout:()=>1, clearTimeout:noop,
  document:{addEventListener:(type,fn)=>(listeners[type]??=[]).push(fn), querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],
    getElementById:()=>({}),createElement:()=>({})}});
const run = code => vm.runInContext(code,ctx);
run(fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8').match(/<script>([\s\S]*?)<\/script>/)[1]);
run(fs.readFileSync(path.join(root,'relay.js'),'utf8'));
const file = path.join(root,'assisted-search.js');
if(fs.existsSync(file))run(fs.readFileSync(file,'utf8'));
assert.equal(run('typeof assistedAnswer'),'function','a separate guided search must exist');
run('const originalRequest=JSON.stringify({...S.req,needs:[...S.req.needs]}); const originalContacts=relay.threads.length;');
assert.equal(run('assistedAnswer(" ")'),false);
assert.equal(run('assistedQuestion().key'),'mode');
run('assistedAnswer("Vacaciones"); assistedAnswer("Cualquier lugar"); assistedAnswer("Fechas flexibles");');
assert.equal(run('assistedAnswer("0")'),false);
run('assistedAnswer("2");');
assert.equal(run('assistedAnswer("500")'),false,'ambiguous currency must not be guessed');
run('assistedAnswer("Sin definir"); assistedAnswer("Ninguno");');
assert.equal(run('assistedQuestion().key'),'refine','many results prompt an optional narrowing question');
run('assistedAnswer("Piscina imprescindible");');
assert.equal(run('assistedResults().length'),3);
assert.equal(run('assistedQuestion().key'),'done');
assert.equal(run('relay.threads.length'),run('originalContacts'));
assert.equal(run('JSON.stringify({...S.req,needs:[...S.req.needs]})'),run('originalRequest'));
run('assistedReset(); assistedAnswer("Para vivir"); assistedAnswer("Heredia"); assistedAnswer("Desde febrero"); assistedAnswer("4"); assistedAnswer("CRC 400000"); assistedAnswer("Mascotas");');
assert.equal(run('assistedResults().map(h=>h.id).join(",")'),'CT-2015');
run('assistedReset(); assistedAnswer("Vacaciones"); assistedAnswer("Guanacaste"); assistedAnswer("3 noches en noviembre"); assistedAnswer("4"); assistedAnswer("CRC 300000"); assistedAnswer("Piscina");');
assert.equal(run('assistedResults().map(h=>h.id).join(",")'),'CT-1042');
run('assisted.criteria.budget=100000;');
assert.equal(run('assistedResults().length'),0,'total stay budget is not a nightly budget');
assert.equal(run('assistedQuestion().key'),'none');
assert.equal(run('assisted.criteria.zone'),'Guanacaste','zero matches do not silently relax conditions');
assert.equal(run('matches({mode:"vac",ppl:2,zone:"Guanacaste",needs:[]}).map(h=>h.id).join(",")'),'CT-1042');
assert.equal(run('matches({mode:"vac",ppl:2,zone:"Cualquier lugar",needs:["Accesible"]}).length'),0,'unknown mandatory amenities must not pass');
run('assistedReset(); assistedAnswer("Vacaciones"); assistedAnswer("<img src=x onerror=alert(1)>");');
assert.equal(run('assistedScreen().includes("<img src=x")'),false);
run('S.loggedIn=true; S.req={mode:"vac",ppl:4,zone:"Guanacaste",dates:"3 noches en noviembre",nights:3,budgetAmount:300000,currency:"₡",needs:new Set(["Piscina"]),text:"Familia"};');
assert.equal(run('submitHouseRequest(false)'),false,'consent is mandatory');
assert.equal(run('submitHouseRequest(true)'),true);
assert.equal(run('S.requests[0].zone'),'Guanacaste');
assert.equal(run('S.requests[0].recipients.join(",")'),'CT-1042');
assert.equal(run('S.requests[0].offers.length'),0,'a sent request does not fabricate owner replies');
run('S.req.nights=null;S.req.budgetAmount=1;');
assert.equal(run('matches(S.req).length'),0,'a missing night count cannot turn the total price into zero');
assert.equal(run('submitHouseRequest(true)'),false);
run('assisted.criteria={mode:"vac",zone:"Guanacaste",dates:"Flexible",ppl:2,budget:null,needs:["Piscina"],needsSet:true}; assistedEdit("zone");');
assert.equal(run('assistedScreen().includes("data-assist-results")'),false,'editing an answer must not expose results with that constraint silently removed');
run('S.req.zone="Cartago";');
assert.equal(run('submitHouseRequest(true)'),false,'cannot send without compatible verified houses');
for(const fn of listeners.input||[])fn({target:{id:'r-budget',value:'300000'}});
assert.equal(run('S.req.budgetAmount'),300000,'input must survive a render even before blur/change');
run('S.req.zone="Guanacaste";S.req.nights=3;S.req.budgetAmount=NaN;');
assert.equal(run('matches(S.req).length'),0,'invalid budget must not mean unlimited');
console.log('PASS: separate guided search, required filters, budget validation, adaptive questions, isolation and escaped text.');

// «Largo plazo» → «Mensual» en toda la interfaz (la landing comercial se conserva tal cual).
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../../design/prototype'),noop=()=>{},storage=new Map();
const ctx=vm.createContext({console,setTimeout:()=>1,clearTimeout:noop,localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},document:{addEventListener:noop,querySelector:()=>({scrollTop:0}),querySelectorAll:()=>[],getElementById:()=>({})}});
const run=s=>vm.runInContext(s,ctx),html=fs.readFileSync(path.join(root,'casatica-prototipo.html'),'utf8');
for(const s of html.matchAll(/<script(?: src="([^"]+)")?>([\s\S]*?)<\/script>/g))run(s[1]?fs.readFileSync(path.join(root,s[1].split('?')[0]),'utf8'):s[2]);
run("S.role='guest';S.filters.prov='Todas';");
const home=run('SCREENS.home()');
assert.match(home,/data-mode="largo"[^>]*>Mensual</);
assert.doesNotMatch(home,/largo plazo/i);
run("S.mode='largo';S.params={id:'CT-2007'};");
assert.doesNotMatch(run('SCREENS.detail()'),/largo plazo/i);
run("S.role='owner';accountAccess.start('register','Marcela','+506 80000002');accountAccess.verify('123456');publicationReset();S.wizStep=1;");
assert.match(run("SCREENS['o-new']()"),/¿Aceptás alquiler mensual\?/);
run("publicationSet('acceptsLongTerm','yes');S.wizStep=5;");
assert.match(run("SCREENS['o-new']()"),/Alquiler mensual/);
assert.doesNotMatch(run("SCREENS['o-new']()"),/largo plazo/i);
run("S.role='admin';adminOpenReview(0);");
assert.match(run("SCREENS['a-review']()"),/Acepta alquiler mensual/);
assert.equal(run('SCREENS.landing()'),run('landing()'),'landing untouched');
console.log('copy-mensual ok');

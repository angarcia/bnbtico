import { expect, test } from "./helpers/test";
import { injectSession } from "./helpers/session";
import { postgrestHarness } from "../db/postgrest-harness";
import { localSupabase } from "../db/local";
import type { SubscriptionHarness } from "../contract/harness";
import { createAirbnbService } from "../../src/data/postgrest/airbnb";
import { runAirbnbImport } from "../../src/server/airbnb";
import { calendarEvent, calendarFile, TEST_AIRBNB_URL } from "../fixtures/airbnb-ical";
import { addDays, longDateWithYear } from "../../src/domain/dates";
import { costaRicaToday } from "../../src/domain/inquiry";

let h: SubscriptionHarness;
test.describe.configure({ mode: "serial" });
test.beforeAll(async () => { h = await postgrestHarness(); await h.reset(); });
const day = (n: number) => addDays(costaRicaToday(Date.now()), n);

test("conectar Airbnb muestra carga, importa por casa y conserva el contexto al volver", async ({ page }) => {
  const l = await h.seed({ status: "active", draft: { title: "Casa prueba iCal" } });
  await h.calendar("owner").save(l.id, { days: [day(11)], available: false, priceCrc: 75000 });
  await injectSession(page, "owner");
  const cfg = localSupabase();
  const service = createAirbnbService({ supabaseUrl: cfg.url, anonKey: cfg.anonKey, serviceKey: cfg.serviceKey, fetch: (i, init) => fetch(i, init) });
  let release: () => void = () => {};
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/calendarios/airbnb", async route => {
    await gate;
    const raw: unknown = route.request().postDataJSON();
    if (!raw || typeof raw !== "object" || !("listingId" in raw) || !("url" in raw) || !("requestId" in raw) || typeof raw.listingId !== "string" || typeof raw.url !== "string" || typeof raw.requestId !== "string") throw new Error("Solicitud no válida");
    const jwt = route.request().headers().authorization?.replace(/^Bearer /, "") ?? "";
    await service.begin(jwt, raw.listingId, raw.url, raw.requestId);
    await runAirbnbImport(service, raw.listingId, raw.requestId, { fetch: async () => new Response(calendarFile(calendarEvent("e2e-falso", day(10).replaceAll("-", ""), day(13).replaceAll("-", "")))) });
    await route.fulfill({ json: await service.overview(jwt, raw.listingId) });
  });
  const month = day(10).slice(0, 7);
  await page.goto(`/propietario/calendario?casa=${l.id}&mes=${month}`);
  await page.getByRole("button", { name: "Conectar con Airbnb" }).click();
  await expect(page.getByRole("heading", { name: "Calendarios de Airbnb" })).toBeVisible();
  await expect(page.getByText("Casa prueba iCal", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Conectar Airbnb", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Conectar Airbnb" });
  await dialog.getByLabel("Enlace de calendario de Airbnb").fill(TEST_AIRBNB_URL);
  await dialog.getByRole("button", { name: "Conectar", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Conectando…" })).toBeDisabled();
  release();
  await expect(dialog).toBeHidden();
  await expect(page.getByText("3 noches bloqueadas por Airbnb", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Actualizar ahora" })).toHaveCount(0);
  await page.getByRole("link", { name: "Volver", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`casa=${l.id}.*mes=${month}`));
  const days = await h.calendar("owner").days(l.id);
  expect(days.find(d => d.day === day(11))).toMatchObject({ imported: true, manualAvailable: false, specialPriceCrc: 75000 });
  const occupied = page.getByRole("button", { name: new RegExp(`^${longDateWithYear(day(11))},`) });
  await expect(page.getByText("Bloqueado por Airbnb", { exact: true })).toBeVisible();
  await expect(occupied.locator(".day-imported svg")).toBeVisible();
  await expect(occupied.locator(".day-sub")).toContainText("75");
  await occupied.click();
  const panel = page.getByRole("region", { name: "Días seleccionados" });
  await expect(panel.getByText("Bloqueo manual y Airbnb", { exact: true })).toBeVisible();
  await panel.getByRole("button", { name: "Quitar bloqueo manual" }).click();
  await panel.getByRole("button", { name: "Guardar cambios" }).click();
  await expect(panel).toBeHidden();
  await occupied.click();
  await expect(panel.getByText("Ocupado por Airbnb · sin bloqueo manual", { exact: true })).toBeVisible();
  await panel.getByRole("button", { name: "Cancelar", exact: true }).click();
});

test("un fallo de lectura conserva campo y estado sin anunciar una conexión", async ({ page }) => {
  const l = await h.seed({ status: "active", draft: { title: "Casa iCal fallo" } });
  await injectSession(page, "owner");
  await page.route("**/api/calendarios/airbnb", route => route.fulfill({ status: 422, json: { code: "download" } }));
  await page.goto(`/propietario/casas/${l.id}/airbnb`);
  await page.getByRole("button", { name: "Conectar Airbnb", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Conectar Airbnb" });
  await dialog.getByLabel("Enlace de calendario de Airbnb").fill(TEST_AIRBNB_URL);
  await dialog.getByRole("button", { name: "Conectar", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("No pudimos leer el calendario");
  await expect(dialog.getByLabel("Enlace de calendario de Airbnb")).toHaveValue(TEST_AIRBNB_URL);
  await dialog.getByRole("button", { name: "Cancelar" }).click();
  await expect(page.getByRole("button", { name: "Conectar Airbnb", exact: true })).toBeVisible();
});
